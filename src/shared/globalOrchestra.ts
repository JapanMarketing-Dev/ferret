/**
 * 「グローバル」のオーケストラ（登録したプロジェクトの全部が対象）の、画面に依存しない純粋な処理。
 * 書き込みは src/main/globalOrchestra.ts。Agent が読む文は英語、人が書く部分の雛形は画面の言語。
 *
 * 全体のルールは、グローバルのフォルダの rules.md（人か、そこの Agent が書く）。Ferret はその中身を
 * - すべてのオーケストラの CLAUDE.md・AGENTS.md の Ferret の欄と、各 subagent（@shared/orchestrator の OrchestraRules.global）
 * - Claude Code の利用者のルール（<設定のフォルダ>/rules/ferret-global-rules.md。Ferret だけが持つファイル）
 * - Codex の全体の AGENTS.md の、印で囲んだ欄（印の外の利用者の文には触れない）
 * へ写す。プロジェクトのフォルダには書かない（各プロジェクトの git を汚さない）
 */

export const GLOBAL_FOLDER_NAME = 'global'
export const GLOBAL_RULES_FILE = 'rules.md'
export const GLOBAL_PROJECTS_FILE = 'projects.md'
/** Claude Code の <設定のフォルダ>/rules/ に置く、Ferret だけが持つファイル */
export const CLAUDE_GLOBAL_RULES_FILE = 'ferret-global-rules.md'
export const GLOBAL_RULES_MARKER = '<!-- ferret-global-rules: generated by Ferret from the Global orchestra\'s rules.md. Ferret rewrites or removes this file; local edits are overwritten. -->'
export const CODEX_BLOCK_START = '<!-- ferret-global-rules:start (generated by Ferret from the Global orchestra\'s rules.md; edits inside this block are overwritten) -->'
export const CODEX_BLOCK_END = '<!-- ferret-global-rules:end -->'

/** 写す中身の上限（subagent・CLAUDE.md を大きくしすぎない。オーケストラのルールと同じ） */
export const MAX_GLOBAL_RULES_CHARS = 8000

export function isFerretGlobalRules(text: string): boolean {
  return text.includes(GLOBAL_RULES_MARKER)
}

/**
 * rules.md から写す中身。コメント（<!-- -->）・先頭の見出し（# …）・中身の無い箇条（- だけ）を外し、前後の空行を詰める。
 * 雛形のままなら空文字
 */
export function globalRulesBody(text: string | null | undefined): string {
  if (!text) return ''
  // 外したあとにまたコメントができることがあるので、変わらなくなるまで繰り返す
  let plain = text.replace(/\r\n?/g, '\n')
  let before: string
  do {
    before = plain
    plain = plain.replace(/<!--[\s\S]*?-->/g, '')
  } while (plain !== before)
  const lines = plain.split('\n')
  const firstContent = lines.findIndex((l) => l.trim() !== '')
  if (firstContent >= 0 && /^#\s/.test(lines[firstContent]!.trim())) lines.splice(firstContent, 1)
  const body = lines
    .filter((l) => !/^\s*[-*]\s*$/.test(l))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
  return body.length > MAX_GLOBAL_RULES_CHARS ? body.slice(0, MAX_GLOBAL_RULES_CHARS).trimEnd() : body
}

/** rules.md の雛形（無いときだけ作る。あとは人と Agent が書く） */
export function globalRulesTemplate(lang: 'ja' | 'en'): string {
  return lang === 'ja'
    ? ['# 全体のルール（すべてのプロジェクト）', '', '<!-- Ferret に登録したすべてのプロジェクトで守ってほしいことを書きます（1行に1つ）。Ferret が、すべてのオーケストラと、Claude Code・Codex の全体の指示へ写します。この印の中は写しません。 -->', '- ', ''].join('\n')
    : ['# Global rules (all projects)', '', '<!-- Rules every project registered in Ferret must follow, one per line. Ferret copies them into every orchestra and into Claude Code\'s and Codex\'s global instructions. Text inside these comment markers is not copied. -->', '- ', ''].join('\n')
}

/** Claude Code の <設定のフォルダ>/rules/ferret-global-rules.md の中身。ルールが空なら null（ファイルを消す） */
export function renderClaudeGlobalRules(body: string, rulesPath: string): string | null {
  if (!body.trim()) return null
  return [
    GLOBAL_RULES_MARKER,
    '',
    '# Global rules (from Ferret)',
    '',
    `These rules apply to every project. They come from \`${rulesPath}\` (Ferret's Global orchestra); to change them, edit that file, not this one. A project's own CLAUDE.md / AGENTS.md wins where it is more specific.`,
    '',
    body.trim(),
    ''
  ].join('\n')
}

/** Codex の全体の AGENTS.md に入れる欄（印で囲む） */
export function renderCodexGlobalBlock(body: string, rulesPath: string): string {
  return [
    CODEX_BLOCK_START,
    '## Global rules (from Ferret)',
    '',
    `These rules apply to every project. They come from \`${rulesPath}\` (Ferret's Global orchestra); to change them, edit that file. A project's own AGENTS.md wins where it is more specific.`,
    '',
    body.trim(),
    CODEX_BLOCK_END
  ].join('\n')
}

/**
 * Codex の AGENTS.md に欄を入れる・差し替える・外した中身。block が null なら欄を外す。変わらなければ null。
 * 印の外（利用者の文）はそのまま。ファイルが無く欄も要らないなら null（作らない）。欄だけになったファイルは空にせず残す（利用者のファイルの扱いは利用者に任せる）
 */
export function withCodexGlobalBlock(existing: string | null, block: string | null): string | null {
  const current = existing ?? ''
  const start = current.indexOf(CODEX_BLOCK_START)
  const end = start >= 0 ? current.indexOf(CODEX_BLOCK_END, start + 1) : -1
  const has = start >= 0 && end > start
  if (block === null) {
    if (!has) return null
    const before = current.slice(0, start).replace(/\s*$/, '')
    const after = current.slice(end + CODEX_BLOCK_END.length).trim()
    const next = [before, after].filter(Boolean).join('\n\n')
    return next ? `${next}\n` : ''
  }
  const next = has
    ? current.slice(0, start) + block + current.slice(end + CODEX_BLOCK_END.length)
    : current.trim() ? `${current.replace(/\s*$/, '')}\n\n${block}\n` : `${block}\n`
  return next === existing ? null : next
}

