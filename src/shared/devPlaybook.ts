/** playbook.md から写す中身 */
export function devPlaybookBody(text: string | null | undefined): string {
  return markdownBody(text, MAX_DEV_PLAYBOOK_CHARS)
}

/**
 * 見出しを写す先の深さに合わせる（いちばん浅い見出しを level にし、ほかも同じだけずらす。6 で止める）。
 * コードの囲み（```）の中は変えない
 */
export function nestHeadings(text: string, level: number): string {
  const lines = text.split('\n')
  let fenced = false
  const isHeading = lines.map((l) => {
    if (/^\s*```/.test(l)) { fenced = !fenced; return 0 }
    const m = !fenced && /^(#{1,6})\s/.exec(l)
    return m ? m[1]!.length : 0
  })
  const levels = isHeading.filter((n) => n > 0)
  if (!levels.length) return text
  const shift = level - Math.min(...levels)
  return lines.map((l, i) => {
    const n = isHeading[i]!
    return n ? `${'#'.repeat(Math.min(6, Math.max(1, n + shift)))}${l.slice(n)}` : l
  }).join('\n')
}

/** 写すときに方針の前に置く一文（人が選んだ方針であること・安全と人の指示とプロジェクトのルールを上書きしないこと） */
export function devPlaybookPreamble(dir: string): string {
  return `The person's chosen practices for building and shipping software with AI agents, distilled from sources they picked (per-source summaries and reasons: \`${dir}/${DEV_PLAYBOOK_DIGESTS_DIR}/\`). Apply them in every project. They never override safety rules, the person's direct instructions, or a project's own CLAUDE.md / AGENTS.md where that is more specific.`
}

/** オーケストラの欄と subagent に入れる開発方針（OrchestraRules.playbook）。前置きと、見出しを #### からにした中身。空なら空文字 */
export function orchestraPlaybookText(body: string, dir: string): string {
  const text = body.trim()
  return text ? `${devPlaybookPreamble(dir)}\n\n${nestHeadings(text, 4)}` : ''
}

