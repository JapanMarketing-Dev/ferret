/** 写す方針の上限。rules.md（MAX_GLOBAL_RULES_CHARS）とは別に持ち、ルールを押し出さない */
export const MAX_DEV_PLAYBOOK_CHARS = 6000
/** Agent に頼むまとめの目安（上限より少し小さく） */
export const DEV_PLAYBOOK_TARGET_CHARS = 5000
export const MAX_DEV_PLAYBOOK_SOURCES = 200
/** 貼り付ける文の上限 */
export const MAX_SOURCE_TEXT_CHARS = 100_000
/** URL の上限 */
export const MAX_SOURCE_URL_CHARS = 2000
/** 選べるファイルの大きさの上限 */
export const MAX_SOURCE_FILE_BYTES = 20 * 1024 * 1024
/** 選べるファイルの種類 */
export const SOURCE_FILE_EXTENSIONS = ['md', 'markdown', 'txt', 'pdf', 'html', 'htm', 'vtt', 'srt', 'json', 'csv'] as const
const TITLE_MAX = 120

export type DevPlaybookSourceKind = 'youtube' | 'web' | 'text' | 'file'
/** pending: まだ Agent に渡せていない / digesting: 取り込み中 / done: 反映済み / failed: 失敗 */
export type DevPlaybookStatus = 'pending' | 'digesting' | 'done' | 'failed'

export interface DevPlaybookSource {
  /** s- で始まる英小文字・数字・ハイフン */
  id: string
  kind: DevPlaybookSourceKind
  /** youtube・web の URL（http・https だけ） */
  url?: string
  /** text・file の写しのファイル名（inputs/ の中） */
  input?: string
  title: string
  addedAt: string
  status: DevPlaybookStatus
  /** 最後に Agent に渡した時刻（これより新しい sources/<id>.md と playbook.md で反映済みにする） */
  requestedAt?: string
  digestedAt?: string
  /** 失敗の理由（Agent が sources/<id>.md に書いたもの） */
  error?: string
  /** 方針に入れるか（外すと次の作り直しで方針から消える） */
  enabled: boolean
}

export interface DevPlaybookFile {
  version: 1
  sources: DevPlaybookSource[]
  /** 入れる・外す・消すを最後に変えた時刻（これより playbook.md が古ければ作り直しが要る） */
  changedAt?: string
  /** 作り直しを最後に頼んだ時刻 */
  rebuildRequestedAt?: string
}

/** 画面に出す状態 */
export interface DevPlaybookState {
  /** グローバルのオーケストラがあり、隠していない */
  available: boolean
  sources: DevPlaybookSource[]
  /** playbook.md の絶対パス */
  playbookPath: string | null
  /** 方針に中身があるか（雛形のままでない） */
  hasPlaybook: boolean
  /** none: 作り直し不要 / needed: 入れる・外すを変えたので作り直しが要る / running: 作り直しを頼んだ */
  rebuild: 'none' | 'needed' | 'running'
}

export const EMPTY_DEV_PLAYBOOK: DevPlaybookFile = { version: 1, sources: [] }

const KINDS: readonly DevPlaybookSourceKind[] = ['youtube', 'web', 'text', 'file']
const STATUSES: readonly DevPlaybookStatus[] = ['pending', 'digesting', 'done', 'failed']
const ID_PATTERN = /^s-[a-z0-9-]{1,40}$/
const INPUT_PATTERN = /^s-[a-z0-9-]{1,40}\.[a-z0-9]{1,10}$/

// ───────────── 入力の見分け ─────────────

export type SourceInput =
  | { ok: true; kind: 'youtube' | 'web'; url: string }
  | { ok: true; kind: 'text'; text: string }
  | { ok: false; reason: 'empty' | 'tooLong' | 'badUrl' }

/** YouTube の動画の id（youtube.com/watch?v=・youtu.be/・/shorts/・/live/・/embed/）。動画でなければ null */
export function youtubeVideoId(url: URL): string | null {
  const host = url.hostname.toLowerCase().replace(/^(www\.|m\.|music\.)/, '')
  const valid = (id: string | null | undefined) => (id && /^[\w-]{6,20}$/.test(id) ? id : null)
  if (host === 'youtu.be') return valid(url.pathname.split('/')[1])
  if (host !== 'youtube.com' && host !== 'youtube-nocookie.com') return null
  if (url.pathname === '/watch') return valid(url.searchParams.get('v'))
  const m = /^\/(?:shorts|live|embed)\/([^/]+)/.exec(url.pathname)
  return valid(m?.[1])
}

/** 同じものを2回取り込まないための URL の形（YouTube は watch?v= に揃え、ほかは # を外す） */
export function canonicalSourceUrl(raw: string): string | null {
  let url: URL
  try { url = new URL(raw) } catch { return null }
  if (url.protocol !== 'http:' && url.protocol !== 'https:') return null
  if (url.username || url.password) return null
  const video = youtubeVideoId(url)
  if (video) return `https://www.youtube.com/watch?v=${video}`
  url.hash = ''
  return url.toString()
}

/**
 * 入力欄の1つの値を、URL（YouTube・web）か貼り付けた文に分ける。
 * 空白を含まない1語で「何か:」で始まるものは URL として扱い、http・https 以外（file:・javascript: など）は断る
 */
export function classifySourceInput(raw: unknown): SourceInput {
  if (typeof raw !== 'string') return { ok: false, reason: 'empty' }
  const value = raw.replace(/\r\n?/g, '\n').trim()
  if (!value) return { ok: false, reason: 'empty' }
  if (!/\s/.test(value) && /^[a-z][a-z0-9+.-]*:/i.test(value)) {
    if (value.length > MAX_SOURCE_URL_CHARS) return { ok: false, reason: 'tooLong' }
    const url = canonicalSourceUrl(value)
    if (!url) return { ok: false, reason: 'badUrl' }
    return { ok: true, kind: youtubeVideoId(new URL(url)) ? 'youtube' : 'web', url }
  }
  if (value.length > MAX_SOURCE_TEXT_CHARS) return { ok: false, reason: 'tooLong' }
  return { ok: true, kind: 'text', text: value }
}

/** 一覧に出す仮の題名（Agent が要約を書いたら、その見出しに置き換える） */
export function provisionalTitle(input: { kind: DevPlaybookSourceKind; url?: string; text?: string; fileName?: string }): string {
  if (input.kind === 'text') {
    const first = (input.text ?? '').split('\n').map((l) => l.replace(/^[#>*\-\s]+/, '').trim()).find(Boolean) ?? ''
    return clip(first) || 'Text'
  }
  if (input.kind === 'file') return clip(input.fileName ?? '') || 'File'
  try {
    const url = new URL(input.url ?? '')
    const path = url.pathname === '/' ? '' : url.pathname
    return clip(`${url.hostname.replace(/^www\./, '')}${path}${url.search}`)
  } catch {
    return clip(input.url ?? '') || 'URL'
  }
}

function clip(text: string): string {
  const one = text.replace(/[\u0000-\u001f\u007f]+/g, ' ').replace(/\s+/g, ' ').trim()
  return one.length > TITLE_MAX ? `${one.slice(0, TITLE_MAX - 1)}…` : one
}

/** 新しい id（時刻と乱数。rand は 0〜1） */
export function newSourceId(now: Date, rand: number): string {
  return `s-${now.getTime().toString(36)}-${Math.floor(rand * 36 ** 4).toString(36).padStart(4, '0')}`
}

/** ファイルの拡張子（小文字）。選べない種類なら null */
export function sourceFileExtension(name: string): string | null {
  const m = /\.([A-Za-z0-9]{1,10})$/.exec(name)
  const ext = m?.[1]?.toLowerCase()
  return ext && (SOURCE_FILE_EXTENSIONS as readonly string[]).includes(ext) ? ext : null
}

// ───────────── sources.json ─────────────

function isoOrUndefined(v: unknown): string | undefined {
  return typeof v === 'string' && v.length <= 40 && !Number.isNaN(Date.parse(v)) ? new Date(v).toISOString() : undefined
}

function sanitizeSource(raw: unknown): DevPlaybookSource | null {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null
  const r = raw as Record<string, unknown>
  if (typeof r.id !== 'string' || !ID_PATTERN.test(r.id)) return null
  const kind = KINDS.find((k) => k === r.kind)
  if (!kind) return null
  const addedAt = isoOrUndefined(r.addedAt)
  if (!addedAt) return null
  const source: DevPlaybookSource = {
    id: r.id,
    kind,
    title: typeof r.title === 'string' ? clip(r.title) : '',
    addedAt,
    status: STATUSES.find((s) => s === r.status) ?? 'pending',
    enabled: r.enabled !== false
  }
  if (kind === 'youtube' || kind === 'web') {
    const url = typeof r.url === 'string' && r.url.length <= MAX_SOURCE_URL_CHARS ? canonicalSourceUrl(r.url) : null
    if (!url) return null
    source.url = url
  } else {
    if (typeof r.input !== 'string' || !INPUT_PATTERN.test(r.input) || !r.input.startsWith(`${r.id}.`)) return null
    source.input = r.input
  }
  if (!source.title) source.title = provisionalTitle({ kind, url: source.url, fileName: source.input })
  const requestedAt = isoOrUndefined(r.requestedAt)
  if (requestedAt) source.requestedAt = requestedAt
  const digestedAt = isoOrUndefined(r.digestedAt)
  if (digestedAt) source.digestedAt = digestedAt
  if (typeof r.error === 'string' && r.error.trim()) source.error = clip(r.error)
  return source
}

/** sources.json を読んだもの（壊れた行・同じ id・同じ URL の2つ目は外す） */
export function sanitizeDevPlaybookFile(raw: unknown): DevPlaybookFile {
  const obj = raw && typeof raw === 'object' && !Array.isArray(raw) ? raw as Record<string, unknown> : {}
  const list = Array.isArray(raw) ? raw : Array.isArray(obj.sources) ? obj.sources : []
  const seen = new Set<string>()
  const sources: DevPlaybookSource[] = []
  for (const item of list) {
    const source = sanitizeSource(item)
    if (!source) continue
    const key = source.url ? `u:${source.url}` : `i:${source.id}`
    if (seen.has(source.id) || seen.has(key)) continue
    seen.add(source.id)
    seen.add(key)
    sources.push(source)
    if (sources.length >= MAX_DEV_PLAYBOOK_SOURCES) break
  }
  const changedAt = isoOrUndefined(obj.changedAt)
  const rebuildRequestedAt = isoOrUndefined(obj.rebuildRequestedAt)
  return { version: 1, sources, ...(changedAt ? { changedAt } : {}), ...(rebuildRequestedAt ? { rebuildRequestedAt } : {}) }
}

export function serializeDevPlaybookFile(file: DevPlaybookFile): string {
  return `${JSON.stringify(file, null, 2)}\n`
}

/** 足す。同じ URL がもうあればそれを返す（duplicate）。上限なら null */
export function addSource(file: DevPlaybookFile, source: DevPlaybookSource): { file: DevPlaybookFile; source: DevPlaybookSource; duplicate: boolean } | null {
  const existing = source.url ? file.sources.find((s) => s.url === source.url) : undefined
  if (existing) return { file, source: existing, duplicate: true }
  if (file.sources.length >= MAX_DEV_PLAYBOOK_SOURCES) return null
  return { file: { ...file, sources: [source, ...file.sources] }, source, duplicate: false }
}

export function updateSource(file: DevPlaybookFile, id: string, patch: Partial<Omit<DevPlaybookSource, 'id' | 'kind'>>): DevPlaybookFile {
  if (!file.sources.some((s) => s.id === id)) return file
  return { ...file, sources: file.sources.map((s) => (s.id === id ? { ...s, ...patch } : s)) }
}

/** 入れる・外す。反映済みのものを変えたら作り直しが要る（changedAt） */
export function setSourceEnabled(file: DevPlaybookFile, id: string, enabled: boolean, now: Date): DevPlaybookFile {
  const source = file.sources.find((s) => s.id === id)
  if (!source || source.enabled === enabled) return file
  const next = updateSource(file, id, { enabled })
  return source.status === 'done' ? { ...next, changedAt: now.toISOString() } : next
}

export function removeSource(file: DevPlaybookFile, id: string, now: Date): DevPlaybookFile {
  const source = file.sources.find((s) => s.id === id)
  if (!source) return file
  const next = { ...file, sources: file.sources.filter((s) => s.id !== id) }
  return source.status === 'done' && source.enabled ? { ...next, changedAt: now.toISOString() } : next
}

/** Agent に渡した（取り込み中にする） */
export function markRequested(file: DevPlaybookFile, id: string, now: Date): DevPlaybookFile {
  const { error: _drop, ...rest } = file.sources.find((s) => s.id === id) ?? {} as DevPlaybookSource
  if (!rest.id) return file
  return { ...file, sources: file.sources.map((s) => (s.id === id ? { ...rest, status: 'digesting' as const, requestedAt: now.toISOString() } : s)) }
}

// ───────────── Agent が書いたものから状態を決める ─────────────

/** sources/<id>.md の中身から分かること */
export interface DigestFileInfo {
  mtimeMs: number
  text: string
}

/** 要約のファイルが「失敗」を書いたものなら、その理由（先頭の20行の `Status: failed — 理由`） */
export function parseDigestFailure(text: string): string | null {
  const head = text.replace(/\r\n?/g, '\n').split('\n').slice(0, 20).join('\n')
  const m = /^\s*\**status\**\s*:\s*\**\s*failed\**\s*(?:[—–:-]+\s*)?(.*)$/im.exec(head)
  if (!m) return null
  return clip(m[1] ?? '') || 'failed'
}

/** 要約のファイルの題名（最初の # 見出し） */
export function parseDigestTitle(text: string): string | null {
  const m = /^#\s+(.+)$/m.exec(text.replace(/\r\n?/g, '\n').split('\n').slice(0, 20).join('\n'))
  const title = m ? clip(m[1]!.replace(/[`*_]/g, '')) : ''
  return title || null
}

/**
 * Agent が書いた sources/<id>.md と playbook.md から、取り込み中のものを「反映済み」「失敗」にする。
 * - 要約が、渡した時刻より後に書かれ、playbook.md がその要約より後に書かれていれば反映済み（要約の見出しを題名にする）
 * - 要約が「失敗」を書いていれば失敗（playbook.md は待たない）
 * 変わらなければ同じオブジェクトを返す
 */
export function applyDigestResults(file: DevPlaybookFile, digests: ReadonlyMap<string, DigestFileInfo>, playbookMtimeMs: number | null): DevPlaybookFile {
  let changed = false
  const sources = file.sources.map((s) => {
    if (s.status !== 'digesting' && s.status !== 'pending') return s
    const digest = digests.get(s.id)
    if (!digest) return s
    const since = Date.parse(s.requestedAt ?? s.addedAt)
    // ファイルの時刻の丸め（秒の単位の FS）を見込んで少しゆるめる
    if (digest.mtimeMs + 2000 < since) return s
    const failure = parseDigestFailure(digest.text)
    if (failure) {
      changed = true
      return { ...s, status: 'failed' as const, error: failure }
    }
    if (playbookMtimeMs === null || playbookMtimeMs + 2000 < digest.mtimeMs) return s
    changed = true
    const { error: _drop, ...rest } = s
    return { ...rest, status: 'done' as const, digestedAt: new Date(Math.max(digest.mtimeMs, playbookMtimeMs)).toISOString(), title: parseDigestTitle(digest.text) ?? s.title }
  })
  return changed ? { ...file, sources } : file
}

/** 作り直しの状態（入れる・外す・消すのあと、playbook.md が書き直されたか） */
export function rebuildState(file: DevPlaybookFile, playbookMtimeMs: number | null): DevPlaybookState['rebuild'] {
  if (!file.changedAt) return 'none'
  const changed = Date.parse(file.changedAt)
  if (playbookMtimeMs !== null && playbookMtimeMs >= changed) return 'none'
  return file.rebuildRequestedAt && Date.parse(file.rebuildRequestedAt) >= changed ? 'running' : 'needed'
}

