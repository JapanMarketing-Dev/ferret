/**
 * 開発方針（Development playbook）。画面に依存しない純粋な処理（書き込みは src/main/devPlaybook.ts）。
 *
 * 人が YouTube・記事・貼り付けた文・ファイルを「取り込む」と、グローバルのオーケストラの Agent がそれを読んで
 * 「AI で作る・出す」ための具体的なルールに直し、1つの方針（playbook.md）にまとめる。Ferret はその方針を rules.md と一緒に
 * すべてのオーケストラ・Claude Code・Codex の全体の指示へ写す（@shared/globalOrchestra）。
 *
 * グローバルのフォルダの dev-playbook/ に置くもの
 * - sources.json … 取り込んだものの一覧（Ferret が書く。Agent が足すときの形は HOW-TO.md）
 * - inputs/<id>.* … 貼り付けた文・選んだファイルの写し（Agent が読む）
 * - sources/<id>.md … 1つずつの要約とルール（Agent が書く。これと playbook.md が書かれたら Ferret が「反映済み」にする）
 * - playbook.md … まとめた方針（Agent が書き直す。人が直したものが勝つ）
 * - HOW-TO.md … 取り込み方（Ferret が書く。skill から頼まれた Agent もこれに従う）
 * Agent が読む文は英語。
 */
