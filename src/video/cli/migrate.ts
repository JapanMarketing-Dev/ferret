import { existsSync, readFileSync, readdirSync, renameSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { LEGACY_PROJECT_FILE, LEGACY_STATE_DIR, VIDEO_CLI, VIDEO_PROJECT_FILE, VIDEO_STATE_DIR } from '@video/names';
import { generateAgentsMd, loadTemplate } from '@video/templates';

// 旧 Solocut の動画フォルダ（solocut.json・.solocut/）を Ferret の名前（ferret-video.json・.ferret-video/）へ移す。
// 既に新しい名前があるものは触らない（何度実行してもよい）。

/** 旧名だけの動画フォルダか（新しい名前の設定ファイルが無く、旧い名前のものがある） */
export function isLegacyOnly(dir: string): boolean {
  return !existsSync(join(dir, VIDEO_PROJECT_FILE)) && existsSync(join(dir, LEGACY_PROJECT_FILE));
}

/** from（かその上）で一番近い、旧名だけの動画フォルダ。新しい名前の動画フォルダに先に当たったら null */
export function findLegacyProjectDir(from: string): string | null {
  let dir = resolve(from);
  for (;;) {
    if (existsSync(join(dir, VIDEO_PROJECT_FILE))) return null;
    if (existsSync(join(dir, LEGACY_PROJECT_FILE))) return dir;
    const up = dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
}

/** root の下（root 自身と depth 段まで）の、旧名だけの動画フォルダ。node_modules・隠しフォルダ・素材のフォルダは見ない */
export function findLegacyProjects(root: string, depth = 2): string[] {
  const out: string[] = [];
  const walk = (d: string, left: number): void => {
    if (isLegacyOnly(d)) {
      out.push(d);
      return;
    }
    if (left <= 0 || existsSync(join(d, VIDEO_PROJECT_FILE))) return;
    let names: string[];
    try {
      names = readdirSync(d, { withFileTypes: true }).filter((e) => e.isDirectory() && !e.name.startsWith('.') && e.name !== 'node_modules').map((e) => e.name).sort();
    } catch {
      return;
    }
    for (const n of names) walk(join(d, n), left - 1);
  };
  walk(resolve(root), depth);
  return out;
}

export interface MigrateResult {
  dir: string;
  /** 移した・書き直したもの（動画フォルダからの相対） */
  moved: string[];
  /** 新しい名前が既にあって触らなかったもの */
  skipped: string[];
  warnings: string[];
}

const LEGACY_AGENTS_HEADERS = ['<!-- solocut が自動生成したファイルです。', '<!-- Generated by solocut.'];

/** 1つの動画フォルダを移す */
export function migrateProject(dir: string): MigrateResult {
  const r: MigrateResult = { dir, moved: [], skipped: [], warnings: [] };
  const move = (from: string, to: string): void => {
    if (!existsSync(join(dir, from))) return;
    if (existsSync(join(dir, to))) {
      r.skipped.push(from);
      r.warnings.push(`${to} already exists; ${from} was left as it is`);
      return;
    }
    renameSync(join(dir, from), join(dir, to));
    r.moved.push(`${from} → ${to}`);
  };
  if (existsSync(join(dir, VIDEO_PROJECT_FILE))) {
    // 既に新しい名前の動画フォルダ。何もしない
    if (existsSync(join(dir, LEGACY_PROJECT_FILE))) r.skipped.push(LEGACY_PROJECT_FILE);
    if (existsSync(join(dir, LEGACY_STATE_DIR))) r.skipped.push(`${LEGACY_STATE_DIR}/`);
    return r;
  }
  move(LEGACY_PROJECT_FILE, VIDEO_PROJECT_FILE);
  if (existsSync(join(dir, LEGACY_STATE_DIR)) && !statSync(join(dir, LEGACY_STATE_DIR)).isDirectory()) r.warnings.push(`${LEGACY_STATE_DIR} is not a folder; left as it is`);
  else move(LEGACY_STATE_DIR, VIDEO_STATE_DIR);
  if (!r.moved.length) return r;
  rewriteGitignore(dir, r);
  regenerateAgentsMd(dir, r);
  return r;
}

/** .gitignore の .solocut/ の行を .ferret-video/ に（ほかの行は触らない） */
function rewriteGitignore(dir: string, r: MigrateResult): void {
  const f = join(dir, '.gitignore');
  if (!existsSync(f)) return;
  const before = readFileSync(f, 'utf8');
  const after = before
    .split('\n')
    .map((line) => (line.startsWith('#') ? line.replace(/^# solocut:/, `# ${VIDEO_CLI}:`) : line.replace(/^(\/?)\.solocut(?=\/|$)/, `$1${VIDEO_STATE_DIR}`)))
    .join('\n');
  if (after !== before) {
    writeFileSync(f, after);
    r.moved.push('.gitignore');
  }
}

/** 自動生成の AGENTS.md（solocut のコマンドが書いてある）を作り直す。手で書いたものは触らない */
function regenerateAgentsMd(dir: string, r: MigrateResult): void {
  const f = join(dir, 'AGENTS.md');
  if (!existsSync(f)) return;
  const text = readFileSync(f, 'utf8');
  if (!LEGACY_AGENTS_HEADERS.some((h) => text.startsWith(h))) {
    if (/\bsolocut\b/.test(text)) r.warnings.push(`AGENTS.md mentions solocut; replace it with ${VIDEO_CLI} by hand`);
    return;
  }
  try {
    const file = JSON.parse(readFileSync(join(dir, VIDEO_PROJECT_FILE), 'utf8')) as { title?: string; language?: string; template?: { id?: string } };
    const tpl = loadTemplate(file.template?.id ?? 'tech', { extraDirs: [join(dir, 'templates')] });
    writeFileSync(f, generateAgentsMd(tpl, { dir, title: file.title ?? '', lang: file.language === 'en' ? 'en' : 'ja' }));
    r.moved.push('AGENTS.md');
  } catch (e) {
    r.warnings.push(`AGENTS.md was not regenerated: ${(e as Error).message}`);
  }
}
