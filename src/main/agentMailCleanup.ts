import { lstat, readdir, readFile, rm, rmdir, unlink } from 'node:fs/promises'
import { homedir, tmpdir } from 'node:os'
import { join } from 'node:path'
import { AGENT_SKILL_AGENTS, agentConfigDir } from '@shared/agentSkill'

/**
 * 削除した「Agent どうしの依頼（agent mail・ferret-agent コマンド）」の後片付け（2026-11-13 に機能ごと削除）。
 * 前の版の Ferret が入れたものだけを消す。
 *
 * - Claude Code・Codex の skills/ferret-agent-mail/SKILL.md は、Ferret が書いた印のあるものだけを消し、空になったフォルダを消す。
 *   印の無いもの・リンクは触らない
 * - 一時フォルダの受け口（ferret-agent-mail-XXXX。中に bin/ferret-agent-core か bin/ferret-agent.ps1 がある）は、
 *   落ちて残ったものも含めて消す。リンクや中身の違うフォルダは触らない
 */

/** 前の版の skill の名前と、Ferret が書いた印（この文字列を含むものだけを消す） */
export const LEGACY_AGENT_MAIL_SKILL_NAME = 'ferret-agent-mail'
export const LEGACY_AGENT_MAIL_SKILL_MARKER = '<!-- ferret-agent-mail-skill: generated by Ferret.'
/** 前の版が一時フォルダに作った受け口の名前の頭と、Ferret が置いた CLI */
export const LEGACY_AGENT_MAIL_DIR_PREFIX = 'ferret-agent-mail-'
const LEGACY_AGENT_MAIL_CLIS = ['ferret-agent-core', 'ferret-agent.ps1']

export async function removeLegacyAgentMailSkill(home: string = homedir(), env: NodeJS.ProcessEnv = process.env): Promise<string[]> {
  const removed: string[] = []
  for (const agent of AGENT_SKILL_AGENTS) {
    const dir = join(agentConfigDir(agent, env, home, join), 'skills', LEGACY_AGENT_MAIL_SKILL_NAME)
    const path = join(dir, 'SKILL.md')
    const stat = await lstat(path).catch(() => null)
    if (!stat?.isFile()) continue
    const text = await readFile(path, 'utf8').catch(() => null)
    if (text === null || !text.includes(LEGACY_AGENT_MAIL_SKILL_MARKER)) continue
    await unlink(path)
    removed.push(path)
    // 空のときだけ消える（利用者が足したファイルがあれば残す）
    await rmdir(dir).catch(() => undefined)
  }
  return removed
}

export async function removeLegacyAgentMailDirs(base: string = tmpdir()): Promise<string[]> {
  const removed: string[] = []
  const names = await readdir(base).catch(() => [] as string[])
  for (const name of names) {
    if (!name.startsWith(LEGACY_AGENT_MAIL_DIR_PREFIX)) continue
    const dir = join(base, name)
    const stat = await lstat(dir).catch(() => null)
    if (!stat?.isDirectory()) continue
    const bin = await readdir(join(dir, 'bin')).catch(() => [] as string[])
    if (!bin.some((file) => LEGACY_AGENT_MAIL_CLIS.includes(file))) continue
    await rm(dir, { recursive: true, force: true }).catch(() => undefined)
    removed.push(dir)
  }
  return removed
}
